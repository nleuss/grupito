let current: 'en' | 'es' = detect();

function detect(): 'en' | 'es' {
  try {
    const l = (typeof chrome !== 'undefined' && chrome.i18n?.getUILanguage?.()) || navigator.language || 'en';
    return l.toLowerCase().startsWith('es') ? 'es' : 'en';
  } catch {
    return 'en';
  }
}

export function setUiLang(pref: 'auto' | 'en' | 'es') {
  current = pref === 'auto' ? detect() : pref;
}

export function uiLang(): 'en' | 'es' {
  return current;
}

export function t(key: Key, ...args: (string | number)[]): string {
  const s = (current === 'es' ? ES : EN)[key] ?? EN[key] ?? key;
  return args.length ? s.replace(/\{(\d)\}/g, (m, i) => (args[+i] !== undefined ? String(args[+i]) : m)) : s;
}

export type I18nKey = Key;
